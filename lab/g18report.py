"""g18: every number for the script, computed from the run folders -> out/g18/results.json + out/g18/RESULTS-g18.md
(nothing typed by hand). Winner rule: lab/g18jobs.py docstring (written before any row ran).
    python -m lab.g18report
"""
import glob
import json
import os
import statistics

from lab import g18jobs as j

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "out", "g18")


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.mean(xs), 2) if xs else None


def main():
    rows = [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(OUT, "runs", "*", "summary.json")))]
    summ = j.summarize(rows)
    win = j.winner(summ)
    per_arm = {}
    for arm in summ:
        rs = [r for r in rows if r["arm"] == arm]
        t0 = [r for r in rs if r["sampling"] == "t0" and r["rep"] == 1]
        vram = [m.get("size_vram") for r in rs for m in (r.get("api_ps") or [])]
        size = [m.get("size") for r in rs for m in (r.get("api_ps") or [])]
        per_arm[arm] = {
            "settings": j.ARMS[arm], "provenance": rs[0]["provenance"],
            "t0_by_job": {r["job"]: r["outcome"] for r in t0},
            "mean_job_seconds_t0": _mean([r["job_seconds"] for r in t0]),
            "mean_load_seconds": _mean([r["load_seconds"] for r in rs]),
            "mean_write_tps": _mean([r["write_tps"] for r in rs]),
            "offload": sorted({tuple(r["offload"]) for r in rs if r.get("offload")}),
            "api_ps_size_vram_gb": sorted({round(v / 1e9, 2) for v in vram if v}),
            "api_ps_size_gb": sorted({round(v / 1e9, 2) for v in size if v}),
            "draft_loaded": sorted({r["draft_loaded"] for r in rs}),
            "prompt_eval_first": sorted({r["prompt_eval_first"] for r in rs if r["prompt_eval_first"] is not None}),
            "thinking_chars_mean": _mean([r["thinking_chars"] for r in rs]),
            "warm_model": sorted({bool(r.get("warm_model")) for r in rs}), "n_runs": len(rs),
        }
    res = {"source": "out/g18/runs/*/summary.json", "n_runs": len(rows), "summary": summ, "winner": win,
           "per_arm": per_arm}
    json.dump(res, open(os.path.join(OUT, "results.json"), "w"), indent=1, default=list)
    L = ["# RESULTS g18 (generated by lab/g18report.py from out/g18/results.json; do not edit)", "",
         "%d runs. Jobs: %s. Baseline: %s." % (len(rows), ", ".join(j.JOBS), json.dumps(j.ARMS["baseline"])), "",
         "| arm | temp 0 (rep 1) | reps identical | Google x5 | per rep | out of room (t0 / google) | "
         "right/min t0 | job s (t0 mean) | load s | write tok/s | layers on GPU | first prompt tokens |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm, v in summ.items():
        t0, g = v.get("t0", {}), v.get("google", {})
        p = per_arm[arm]
        L.append("| %s | %s | %s | %s | %s | %s / %s | %s | %s | %s | %s | %s | %s |" % (
            arm, t0.get("label"), t0.get("reps_identical"), g.get("label"), g.get("per_rep"),
            t0.get("outcomes", {}).get("ran out of room"), g.get("outcomes", {}).get("ran out of room"),
            t0.get("right_per_minute"), p["mean_job_seconds_t0"], p["mean_load_seconds"], p["mean_write_tps"],
            p["offload"], p["prompt_eval_first"]))
    L += ["", "Temp 0 by job: " + "; ".join("%s %s" % (a, json.dumps(p["t0_by_job"])) for a, p in per_arm.items()),
          "", "**Winner (rule in lab/g18jobs.py):** " + json.dumps(win)]
    open(os.path.join(OUT, "RESULTS-g18.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(json.dumps(win))


if __name__ == "__main__":
    main()
